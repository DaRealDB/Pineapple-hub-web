// POST /api/reports/downtime
// ═══════════════════════════════════════════════════════════════════════

router.post('/downtime', async (req, res) => {
  try {
    const { date, format = 'html', days = 7 } = req.body;
    const generatedBy = req.user?.email || 'Admin User';

    const { rows: gaps } = await ocrQuery(
      `WITH ordered AS (
         SELECT timestamp,
           LAG(timestamp) OVER (ORDER BY timestamp) AS prev_ts
         FROM operations_log
         WHERE timestamp >= ($1::date - ($2 || ' days')::interval)
           AND timestamp <= ($1::date + interval '1 day')
       )
       SELECT prev_ts::text AS from_time, timestamp::text AS to_time,
         EXTRACT(EPOCH FROM (timestamp - prev_ts))::int AS gap_seconds
       FROM ordered
       WHERE EXTRACT(EPOCH FROM (timestamp - prev_ts)) > 60
       ORDER BY gap_seconds DESC
       LIMIT 50`,
      [date, days]
    );

    const { rows: countRows } = await ocrQuery(
      `SELECT COUNT(*)::int AS total_entries,
         COUNT(DISTINCT DATE(timestamp))::int AS active_days
       FROM operations_log
       WHERE timestamp >= ($1::date - ($2 || ' days')::interval)
         AND timestamp <= ($1::date + interval '1 day')`,
      [date, days]
    );
    const c = countRows[0] || {};

    const totalGapSec = gaps.reduce((s, g) => s + (g.gap_seconds || 0), 0);
    const mtbfMin = gaps.length > 0 ? Math.round(totalGapSec / gaps.length / 60) : null;

    const headers = ['From', 'To', 'Gap (s)', 'Gap (min)'];
    const align   = ['left', 'left', 'right', 'right'];
    const dataRows = gaps.map(g => [fmtTs(g.from_time), fmtTs(g.to_time), g.gap_seconds, Math.round(g.gap_seconds / 60)]);

    const hdr = docHeader({ title: 'Device Downtime Log', date, days, generatedBy });

    if (format === 'csv') {
      const summary = `Active Days,${c.active_days || 0}\nTotal Entries,${c.total_entries || 0}\nMTBF (min),${mtbfMin ?? 'N/A'}\n`;
      const csv = summary + '\n' + buildCsv(headers, dataRows);
      return saveAndRespond(res, 'downtime', 'csv', `downtime-${date}`, csv, null, generatedBy);
    }

    if (format === 'xlsx') {
      const buf = buildXlsx([
        { name: 'Downtime Gaps', headers, rows: dataRows, align },
      ]);
      return saveAndRespond(res, 'downtime', 'xlsx', `downtime-${date}`, null, buf, generatedBy);
    }

    const html = buildHtmlReport(`Device Downtime Log — ${date} (${days}-day window)`, [
      hdr,
      { heading: 'Availability Summary', text: `Active Days: ${c.active_days || 0}  |  Total Entries: ${c.total_entries || 0}  |  MTBF: ${mtbfMin ? `${mtbfMin} min` : 'N/A'}  |  Detected Gaps: ${gaps.length}` },
      { heading: 'Detected Gaps (> 60 s between entries)', table: [headers, ...dataRows], align },
    ]);
    saveAndRespond(res, 'downtime', 'html', `downtime-${date}`, html, null, generatedBy);
  } catch (err) {
    console.error('[Reports] downtime error:', err);
    res.status(500).json({ error: 'Report generation failed' });
  }
});

// ═══════════════════════════════════════════════════════════════════════
// GET /api/reports/download/:id
// ═══════════════════════════════════════════════════════════════════════

router.get('/download/:id', async (req, res) => {
  try {
    const { rows } = await query(
      'SELECT file_path, file_name, format FROM grading.report_exports WHERE id = $1',
      [req.params.id]
    );
    if (rows.length === 0) return res.status(404).json({ error: 'Report not found' });

    const r = rows[0];
    if (!fs.existsSync(r.file_path)) return res.status(404).json({ error: 'File missing from disk' });

    const mime = r.format === 'xlsx' ? 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
      : r.format === 'csv' ? 'text/csv' : 'text/html';
    res.setHeader('Content-Type', mime);
    res.setHeader('Content-Disposition', `attachment; filename="${r.file_name}"`);
    res.sendFile(r.file_path);
  } catch (err) {
    console.error('[Reports] download error:', err);
    res.status(500).json({ error: 'Download failed' });
  }
});

